//! export — generadores de código fuente para plataformas de trading.
//! V1: MetaTrader 4 / MetaTrader 5 (Expert Advisors Long-only con la misma
//! lógica del motor: MA cross, RSI reversión, ruptura ATR). Escrito desde cero.

use super::engine::rules::Template;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Platform { Mql4, Mql5 }

impl Platform {
    /// Acepta mql4/mql5 y alias de commerce en cualquier capitalización.
    pub fn from_str(s: &str) -> Option<Self> {
        match s.trim().to_ascii_lowercase().as_str() {
            "mql4" | "mt4" => Some(Platform::Mql4),
            "mql5" | "mt5" => Some(Platform::Mql5),
            _ => None,
        }
    }
}

/// Genera el código fuente completo del EA. `name` es el nombre de la estrategia.
pub fn strategy_code(platform: Platform, name: &str, tmpl: Template, p: [f64; 3]) -> String {
    match platform {
        Platform::Mql4 => mql4(name, tmpl, p),
        Platform::Mql5 => mql5(name, tmpl, p),
    }
}

fn params_block(p: [f64; 3]) -> String {
    format!(
        "input double InpP1 = {p1};\ninput double InpP2 = {p2};\ninput double InpP3 = {p3};",
        p1 = trim_num(p[0]), p2 = trim_num(p[1]), p3 = trim_num(p[2])
    )
}

fn trim_num(v: f64) -> String {
    let s = format!("{v}");
    if s.contains('.') { s } else { s + ".0" }
}

// ── MT5 ────────────────────────────────────────────────────────────

fn mql5(name: &str, tmpl: Template, p: [f64; 3]) -> String {
    format!(
        r#"//+------------------------------------------------------------------+
//| {name} — Expert Advisor generated by SophieQuant (MQL5)   |
//| Estrategia: {tmpl} {params}
//| Long-only con stop/target en ATR. Revisar antes de usar en real.|
//+------------------------------------------------------------------+
#property version   "1.00"
#property strict

#include <Trade\Trade.mqh>

input double InpLots   = 0.10;
input double InpSlAtr  = 2.0;
input double InpTpAtr  = 3.0;
{params_block}

CTrade trade;
bool inPos = false;

int OnInit()  {{ return INIT_SUCCEEDED; }}
void OnDeinit(const int reason) {{}}

void OnTick()
{{
   if (iBars(_Symbol, PERIOD_CURRENT) < 120) return;

{indicator_logic}

   double atrCur = iATR(_Symbol, PERIOD_CURRENT, 14);
   double sl = InpSlAtr * atrCur;
   double tp = (InpTpAtr > 0.0) ? InpTpAtr * atrCur : 0.0;

{execution}
}}
"#,
        tmpl = tmpl.label(),
        params = format!("| {:?}", tmpl.default_params()),
        params_block = params_block(p),
        indicator_logic = mql5_indicator_logic(tmpl),
        execution = mql5_execution(),
    )
}

fn mql5_indicator_logic(tmpl: Template) -> String {
    match tmpl {
        Template::MaCross => r#"   double e1 = iMA(_Symbol, PERIOD_CURRENT, (int)InpP1, 0, MODE_EMA, PRICE_CLOSE, 1);
   double e2 = iMA(_Symbol, PERIOD_CURRENT, (int)InpP1, 0, MODE_EMA, PRICE_CLOSE, 2);
   double s1 = iMA(_Symbol, PERIOD_CURRENT, (int)InpP2, 0, MODE_SMA, PRICE_CLOSE, 1);
   double s2 = iMA(_Symbol, PERIOD_CURRENT, (int)InpP2, 0, MODE_SMA, PRICE_CLOSE, 2);
   bool enter = (e2 <= s2 && e1 > s1);
   bool exitL = (e2 >= s2 && e1 < s1);"#
            .to_string(),
        Template::RsiReversion => r#"   double r1 = iRSI(_Symbol, PERIOD_CURRENT, (int)InpP1, PRICE_CLOSE, 1);
   double r2 = iRSI(_Symbol, PERIOD_CURRENT, (int)InpP1, PRICE_CLOSE, 2);
   bool enter = (r2 >= InpP2 && r1 < InpP2);
   bool exitL = (r2 <= InpP3 && r1 > InpP3);"#
            .to_string(),
        Template::AtrBreakout => r#"   int hiIdx  = iHighest(_Symbol, PERIOD_CURRENT, MODE_HIGH, (int)InpP1, 1);
   int loIdx  = iLowest(_Symbol, PERIOD_CURRENT, MODE_LOW, (int)InpP1, 1);
   double hh  = iHigh(_Symbol, PERIOD_CURRENT, hiIdx);
   double ll  = iLow(_Symbol, PERIOD_CURRENT, loIdx);
   bool enter = (iClose(_Symbol, PERIOD_CURRENT, 1) > hh);
   bool exitL = (iClose(_Symbol, PERIOD_CURRENT, 1) < ll);"#
            .to_string(),
    }
}

fn mql5_execution() -> String {
    r#"   if (!inPos && enter)
   {{
      double ask = SymbolInfoDouble(_Symbol, SYMBOL_ASK);
      double slP = ask - sl;
      double tpP = (tp > 0.0) ? ask + tp : 0.0;
      trade.Buy(NormalizeLot(InpLots), _Symbol, 0.0, NormalizePrice(slP), NormalizePrice(tpP));
      inPos = true;
   }}
   else if (inPos && exitL)
   {{
      trade.PositionClose(_Symbol);
      inPos = false;
   }}
}

double NormalizeLot(double lots)
{
   double step = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_STEP);
   return MathMax(step, MathFloor(lots / step) * step);
}

double NormalizePrice(double price)
{
   int digits = (int)SymbolInfoInteger(_Symbol, SYMBOL_DIGITS);
   return NormalizeDouble(price, digits);
}"#
        .to_string()
}

// ── MT4 ────────────────────────────────────────────────────────────

fn mql4(name: &str, tmpl: Template, p: [f64; 3]) -> String {
    format!(
        r#"//+------------------------------------------------------------------+
//| {name} — Expert Advisor generated by SophieQuant (MQL4)   |
//| Estrategia: {tmpl}  | Long-only, stop/target ATR                 |
//+------------------------------------------------------------------+
#property version "1.00"
#property strict

input double InpLots = 0.10;
input double InpSlAtr = 2.0;
input double InpTpAtr = 3.0;
{params_block}

bool inPos = false;

void OnTick()
{{
   if (Bars < 120) return;

{indicator_logic}

   double atrCur = iATR(_Symbol, 0, 14, 1);
   double sl = InpSlAtr * atrCur;
   double tp = (InpTpAtr > 0.0) ? InpTpAtr * atrCur : 0.0;
   double point = MarketInfo(_Symbol, MODE_POINT);

{execution}
}}
"#,
        tmpl = tmpl.label(),
        params_block = params_block(p),
        indicator_logic = mql4_indicator_logic(tmpl),
        execution = mql4_execution(),
    )
}

fn mql4_indicator_logic(tmpl: Template) -> String {
    match tmpl {
        Template::MaCross => r#"   double e1 = iMA(_Symbol, 0, (int)InpP1, 0, MODE_EMA, PRICE_CLOSE, 1);
   double e2 = iMA(_Symbol, 0, (int)InpP1, 0, MODE_EMA, PRICE_CLOSE, 2);
   double s1 = iMA(_Symbol, 0, (int)InpP2, 0, MODE_SMA, PRICE_CLOSE, 1);
   double s2 = iMA(_Symbol, 0, (int)InpP2, 0, MODE_SMA, PRICE_CLOSE, 2);
   bool enter = (e2 <= s2 && e1 > s1);
   bool exitL = (e2 >= s2 && e1 < s1);"#
            .to_string(),
        Template::RsiReversion => r#"   double r1 = iRSI(_Symbol, 0, (int)InpP1, PRICE_CLOSE, 1);
   double r2 = iRSI(_Symbol, 0, (int)InpP1, PRICE_CLOSE, 2);
   bool enter = (r2 >= InpP2 && r1 < InpP2);
   bool exitL = (r2 <= InpP3 && r1 > InpP3);"#
            .to_string(),
        Template::AtrBreakout => r#"   double hh = High[iHighest(_Symbol, 0, MODE_HIGH, (int)InpP1, 1)];
   double ll = Low[iLowest(_Symbol, 0, MODE_LOW, (int)InpP1, 1)];
   bool enter = (Close[1] > hh);
   bool exitL = (Close[1] < ll);"#
            .to_string(),
    }
}

fn mql4_execution() -> String {
    r#"   if (!inPos && enter)
   {{
      double ask = MarketInfo(_Symbol, MODE_ASK);
      OrderSend(_Symbol, OP_BUY, InpLots, ask, 3,
                NormalizeDouble(ask - sl, Digits),
                (tp > 0.0) ? NormalizeDouble(ask + tp, Digits) : 0,
                "SophieQuant", 0, 0, clrLime);
      inPos = true;
   }}
   else if (inPos && exitL)
   {{
      for (int i = OrdersTotal() - 1; i >= 0; i--)
      {{
         if (!OrderSelect(i, SELECT_BY_POS, MODE_TRADES)) continue;
         if (OrderSymbol() == _Symbol && OrderMagicNumber() == 0)
            OrderClose(OrderTicket(), OrderLots(), MarketInfo(_Symbol, MODE_BID), 3, clrRed);
      }}
      inPos = false;
   }}
}"#
        .to_string()
}
// ── tests de export (golden mínimo: estructura esperada por plataforma) ─
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn from_str_acepta_alias_y_rechaza_raro() {
        assert_eq!(Platform::from_str("mql5"), Some(Platform::Mql5));
        assert_eq!(Platform::from_str("MT5"), Some(Platform::Mql5));
        assert_eq!(Platform::from_str("mql4"), Some(Platform::Mql4));
        assert_eq!(Platform::from_str("weird"), None);
    }

    #[test]
    fn mql5_tiene_inputs_con_defaults_y_ontick() {
        let code = strategy_code(Platform::Mql5, "S001 MA cross", Template::MaCross, [12.0, 48.0, 0.0]);
        assert!(code.contains("input double InpP1 = 12.0"), "P1 default inyectado");
        assert!(code.contains("input double InpP2 = 48.0"));
        assert!(code.contains("OnTick"), "MQL5 usa OnTick: {}", code);
        // nombre de estrategia embebido como comentario
        assert!(code.contains("MA cross"));
        // ningún placeholder sin sustituir
        assert!(!code.contains("{params_block}"), "placeholder params_block sin inyectar");
        assert!(!code.contains("{indicator_logic}"), "placeholder indicator_logic sin inyectar");
        assert!(!code.contains("{execution}"), "placeholder execution sin inyectar");
    }

    #[test]
    fn mql4_y_mql5_son_distintos_y_completos() {
        let m4 = strategy_code(Platform::Mql4, "S001", Template::RsiReversion, [14.0, 30.0, 70.0]);
        let m5 = strategy_code(Platform::Mql5, "S001", Template::RsiReversion, [14.0, 30.0, 70.0]);
        assert_ne!(m4, m5, "las plataformas no comparten código");
        assert!(m4.contains("OrderClose"), "MQL4 usa la API antigua de órdenes");
        assert!(m5.contains("PositionClose") || m5.contains("trade"), "MQL5 usa CTrade o gestión moderna");
    }

    #[test]
    fn los_tres_templates_generan_logica_propia() {
        let a = strategy_code(Platform::Mql5, "x", Template::MaCross, [12.0, 48.0, 0.0]);
        let b = strategy_code(Platform::Mql5, "x", Template::RsiReversion, [14.0, 30.0, 70.0]);
        let c = strategy_code(Platform::Mql5, "x", Template::AtrBreakout, [20.0, 2.0, 3.0]);
        assert_ne!(a, b);
        assert_ne!(b, c);
        assert_ne!(a, c);
    }
}
